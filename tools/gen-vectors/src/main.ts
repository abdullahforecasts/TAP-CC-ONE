/**
 * Generates spec/vectors/ deterministically and checks every vector against its intent.
 *
 *   pnpm vectors:generate   # (re)write the vectors
 *   pnpm vectors:check      # regenerate in memory; fail if any byte differs from the committed files
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createAnchorVerifier } from '@tap/anchor';
import { testTsa } from '@tap/anchor/testing';
import { type SubmittedFile, toHex, utf8, type VerifyOptions, type VerifyReport, verifyLog } from '@tap/core';
import { type ExpectedFinding, VECTORS, type VectorDef } from './vectors.js';

const TEST_ROOT = 'test-tsa-root.pem';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../spec/vectors');

interface GeneratedFile {
  path: string;
  bytes: Uint8Array;
}

function findingKey(f: ExpectedFinding): string {
  return [f.severity, f.code, f.seq ?? '', f.offset ?? ''].join('|');
}

/** Compares the verifier's non-pass findings with the expected list (as multisets). */
function compareFindings(def: VectorDef, report: VerifyReport, expected: ExpectedFinding[]): void {
  // Codes and severities must match exactly; positions only where the vector pins them down.
  const actual: ExpectedFinding[] = report.findings
    .filter((f) => f.severity !== 'pass')
    .map((f) => ({ code: f.code, severity: f.severity as ExpectedFinding['severity'] }));
  const pinned = (f: ExpectedFinding) => f.seq !== undefined || f.offset !== undefined;
  const loose = (f: ExpectedFinding) => findingKey({ code: f.code, severity: f.severity });
  const a = actual.map(loose).sort();
  const e = expected.map(loose).sort();
  if (JSON.stringify(a) !== JSON.stringify(e)) {
    throw new Error(
      `${def.id}: findings differ\n  expected ${JSON.stringify(e)}\n  actual   ${JSON.stringify(a)}`,
    );
  }
  for (const exp of expected.filter(pinned)) {
    const hit = report.findings.find(
      (f) =>
        f.code === exp.code &&
        (exp.seq === undefined || f.seq === exp.seq) &&
        (exp.offset === undefined || f.offset === exp.offset),
    );
    if (!hit) throw new Error(`${def.id}: expected ${exp.code} at ${JSON.stringify(exp)}`);
  }
}

function generate(def: VectorDef): GeneratedFile[] {
  const out = def.build();
  const facts = out.facts ?? {};
  const options: VerifyOptions = out.submission ? { submission: out.submission } : {};
  if (out.trust) {
    const headers = Object.entries(out.trust.bitcoinHeaders ?? {}).map(
      ([h, header]) => [Number(h), header] as const,
    );
    options.anchorVerifier = createAnchorVerifier({
      roots: testTsa().roots,
      bitcoinHeaders: new Map(headers),
    });
  }
  const report = verifyLog(out.log, options);
  if (report.verdict !== def.verdict) {
    throw new Error(
      `${def.id}: verdict ${report.verdict}, expected ${def.verdict}\n${JSON.stringify(report.findings, null, 2)}`,
    );
  }
  const expectedFindings = def.findings(facts);
  compareFindings(def, report, expectedFindings);
  def.check?.(report, facts);

  const dir = `${def.id}-${def.slug}`;
  const expected = {
    id: def.id,
    title: def.title,
    description: def.description,
    verdict: def.verdict,
    findings: expectedFindings,
    recordCount: report.recordCount,
    finalFiles: report.finalFiles,
    composition: report.composition ?? null,
    // Verify timestamp tokens with these trust anchors (paths relative to spec/vectors/).
    ...(out.trust
      ? {
          trust: {
            tsaRoots: [TEST_ROOT],
            bitcoinHeaders: Object.fromEntries(
              Object.entries(out.trust.bitcoinHeaders ?? {}).map(([h, b]) => [h, toHex(b)]),
            ),
          },
          anchoring: report.anchoring ?? null,
        }
      : {}),
    // Paths exactly as submitted (may use '\\'); the files live under submission/ with '/' paths.
    submittedPaths: (out.submission ?? []).map((f: SubmittedFile) => f.path),
  };
  const files: GeneratedFile[] = [
    { path: `${dir}/log.codelog`, bytes: out.log },
    { path: `${dir}/expected.json`, bytes: utf8(`${JSON.stringify(expected, null, 2)}\n`) },
  ];
  for (const file of out.submission ?? []) {
    const content = typeof file.content === 'string' ? utf8(file.content) : file.content;
    files.push({ path: `${dir}/submission/${file.path.replace(/\\/g, '/')}`, bytes: content });
  }
  return files;
}

function index(): GeneratedFile {
  const rows = VECTORS.map(
    (v) => `| ${v.id} | [${v.title}](${v.id}-${v.slug}/) | ${v.verdict.replace(/_/g, ' ')} |`,
  );
  const text = `# Conformance test vectors

Generated by \`pnpm vectors:generate\` (tools/gen-vectors). Do not edit by hand: CI regenerates them
and fails if any byte differs.

Each folder holds:

- \`log.codelog\`: the log file
- \`expected.json\`: verdict, the complete list of non-pass findings, final files and composition
- \`submission/\` (optional): the submitted code to compare against the final logged state

Vectors 001–012 contain no third-party timestamps, so their verdict includes the \`NO_ANCHORS\`
warning ("Intact" in design.md Appendix C means: no integrity failures). Vector 102 uses
placeholder timestamp tokens; it fails on the anchored digests alone.

Vectors 013–015 carry real RFC 3161 and OpenTimestamps proofs from a deterministic test
authority. Their \`expected.json\` has a \`trust\` section: verify the tokens trusting only
\`${TEST_ROOT}\` (never trust it anywhere else) and the listed Bitcoin block headers (hex,
80 bytes, by height). The \`anchoring\` section is the expected summary. The batch-check
vector (106) is added with the verifier part.

| # | Vector | Verdict |
|---|---|---|
${rows.join('\n')}
`;
  return { path: 'README.md', bytes: utf8(text) };
}

function main(): void {
  const check = process.argv.includes('--check');
  const files: GeneratedFile[] = [index(), { path: TEST_ROOT, bytes: utf8(testTsa().rootPem) }];
  for (const def of VECTORS) files.push(...generate(def));

  if (check) {
    const problems: string[] = [];
    for (const f of files) {
      const p = join(ROOT, f.path);
      if (!existsSync(p)) problems.push(`missing ${f.path}`);
      else if (!Buffer.from(readFileSync(p)).equals(Buffer.from(f.bytes))) problems.push(`differs ${f.path}`);
    }
    if (problems.length > 0) {
      console.error(`Vectors are out of date:\n  ${problems.join('\n  ')}\nRun: pnpm vectors:generate`);
      process.exit(1);
    }
    console.log(`All ${VECTORS.length} vectors are up to date and match their intent.`);
    return;
  }

  if (existsSync(ROOT)) {
    for (const entry of readdirSync(ROOT)) rmSync(join(ROOT, entry), { recursive: true, force: true });
  }
  for (const f of files) {
    const p = join(ROOT, f.path);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, f.bytes);
  }
  console.log(`Wrote ${VECTORS.length} vectors (${files.length} files) to spec/vectors/`);
}

main();
